    <h1>NEPCON 2025</h1>
    <h2>General Guidelines</h2>
    <ul>
        <li>Abstract theme should align with the conference theme, regional child health epidemiology, national priorities, or innovations in child health.</li>
        <li>Abstracts must be submitted electronically through the official website portal.</li>
        <li>Only original research, clinical audits, case reports, or case series related to Paediatrics are allowed.</li>
        <li>Do not include tables, figures, or references in the abstract.</li>
        <li>Submission deadline: <strong>April 30, 2025, 11:59 PM</strong>.</li>
        <li>The presenting author must be registered with the congress.</li>
        <li>Authors take full intellectual responsibility for their submissions.</li>
        <li>Ethical clearance is required where applicable.</li>
        <li>Submission implies consent for publication (e.g., website, programs).</li>
        <li>Multiple abstracts are allowed but must be submitted separately.</li>
    </ul>
    
    <h2>Abstract of Research Papers (Original Articles - NOT Case Report/Case Series)</h2>
    <h3>Format of the Abstract</h3>
    <ol>
        <li><span class="bold">Title</span></li>
        <li><span class="bold">Authors/Affiliation</span></li>
        <li><span class="bold">Background</span></li>
        <li><span class="bold">Objective</span></li>
        <li><span class="bold">Methods</span></li>
        <li><span class="bold">Results</span></li>
        <li><span class="bold">Conclusion</span></li>
    </ol>
    
    <h3>Guidelines</h3>
    <ul>
        <li>Minimum of 200 words and maximum of 400 words.</li>
        <li><span class="bold capital">Presenting Author’s Name</span> must be in bold capital letters.</li>
        <li>Abstracts must be in <span class="capital">English</span>.</li>
        <li>Title should be in <span class="capital">capital letters</span>.</li>
        <li>Use <span class="bold">Times New Roman</span>, 12 pt font.</li>
        <li>Text-only content; no tables, images, figures, symbols, diagrams, or graphs.</li>
        <li>Spell out acronyms on first use.</li>
        <li>No references, credits, or grant support in the abstract.</li>
        <li>Correct grammar and spelling must be observed.</li>
        <li>Indicate the year of research completion.</li>
        <li>Indicate previous presentation status (Yes/No).</li>
        <li>Indicate ethics review approval status (Yes/No).</li>
        <li>No revisions or resubmissions after the deadline.</li>
        <li>Cancellation must be done before the deadline.</li>
        <li>Notification of acceptance: May 1-5, 2025.</li>
    </ul>
    
    <h2>Abstract of Interesting Case Report/Case Series</h2>
    <h3>Definition of Terms</h3>
    <ul>
        <li><span class="bold">Case Report:</span> 1 to 5 cases.</li>
        <li><span class="bold">Case Series:</span> 3 to 10 cases.</li>
    </ul>
    
    <h3>Presentation Type</h3>
    <ul>
        <li>Poster</li>
        <li>Oral Presentation</li>
    </ul>
    
    <h3>Format of the Abstract</h3>
    <ol>
        <li><span class="bold">Title</span></li>
        <li><span class="bold">Author Name(s)</span></li>
        <li><span class="bold">Background</span> (1-2 sentences)</li>
        <li><span class="bold">Case Presentation</span> (3-6 sentences)</li>
        <li><span class="bold">Discussion/Conclusion</span> (1-2 sentences)</li>
        <li><span class="bold">Keywords</span> (3-5)</li>
    </ol>
    
    <h3>Guidelines</h3>
    <ul>
        <li>Minimum of 150 words and maximum of 1000 words.</li>
        <li><span class="bold capital">Presenting Author’s Name</span> must be in bold capital letters.</li>
        <li>Abstracts must be in <span class="capital">English</span>.</li>
        <li>Title should be in <span class="capital">capital letters</span>.</li>
        <li>Submit in PDF format.</li>
        <li>Use <span class="bold">Times New Roman</span>, 12 pt font.</li>
        <li>Text-only content; no tables, images, figures, symbols, diagrams, or graphs.</li>
        <li>Spell out acronyms on first use.</li>
        <li>No references, credits, or grant support in the abstract.</li>
        <li>Correct grammar and spelling must be observed.</li>
        <li>Indicate the year of research completion.</li>
        <li>Indicate previous presentation status (Yes/No).</li>
        <li>Indicate ethics review approval status (Yes/No).</li>
        <li>No revisions or resubmissions after the deadline.</li>
        <li>Cancellation must be done before the deadline.</li>
    </ul>
    
    <h2>Poster Preparation, Print, and Presentation</h2>
    <ul>
        <li>Prepare posters in advance and bring a printed hard copy.</li>
        <li>Posters must be put up before <strong>8 AM</strong> on Day 1.</li>
        <li>Recommended poster dimensions: 48″ × 36″, 36″ × 48″, A0, or A1.</li>
        <li>Font must be consistent and legible from 6 feet away (22-28 pt body text).</li>
        <li>Posters will be presented pre-lunch, moderated by experts.</li>
        <li>Presentation: <strong>7 minutes</strong> + <strong>5 minutes</strong> for discussion.</li>
        <li><strong>Prizes:</strong> First, Second, and Third will be announced at the end of the day.</li>
    </ul>
